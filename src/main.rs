#[derive(clap::Parser)]
enum Cli {
    Encode {
        #[clap(short, long)]
        mode: Mode,

        #[clap(short, long)]
        blueprint: bool,

        /// Path to data-raw-dump.json.gz
        ///
        /// Generated by `factorio --dump-data --mod-directory <DIR>`
        data: PathBuf,
    },
    Decode {
        blueprint: String,
    },
}

#[derive(Copy, Clone, clap::ValueEnum)]
enum Mode {
    Priority,
    CraftTime,
    InputCount,
}

fn main() {
    match Cli::parse() {
        Cli::Decode { blueprint } => {
            BlueprintString::with_decode(&blueprint, |blueprint| {
                println!("{:#?}", blueprint);
            });
        }
        Cli::Encode {
            mode,
            blueprint,
            data,
        } => {
            let mut buffer = Vec::new();
            File::open(&data)
                .map(BufReader::new)
                .map(flate2::read::GzDecoder::new)
                .unwrap()
                .read_to_end(&mut buffer)
                .unwrap();

            let data = serde_json::from_slice::<Data>(&buffer).unwrap();

            let categories = data
                .machines
                .iter()
                .filter(|(name, _)| name.starts_with("automated-factory"))
                .flat_map(|(_, machine)| &machine.categories)
                .copied()
                .collect::<HashSet<&str>>();

            let enabled = data
                .technologies
                .iter()
                .flat_map(|(_, technology)| {
                    technology.effects.iter().filter_map(|effect| match effect {
                        Effect::UnlockRecipe { recipe } => Some(*recipe),
                        Effect::Other => None,
                    })
                })
                .collect::<HashSet<_>>();

            let mut craftable = HashMap::new();

            let graph = data
                .recipes
                .iter()
                // methanol <-> methanol-gas-canister <-> empty-gas-canister
                .filter(|(name, _)| !name.contains("canister"))
                .filter(|(name, _)| !name.contains("cage"))
                .filter(|(name, _)| !name.contains("barrel"))
                // // nuclear-reactor <-> nuclear-reactor-mox
                .filter(|(name, _)| !name.ends_with("uncraft"))
                // recipe-unknown
                .filter(|(_, recipe)| !recipe.results.is_empty())
                .filter(|(name, recipe)| recipe.enabled || enabled.contains(name))
                .filter(|(name, recipe)| {
                    assert!(recipe.categories.len() <= 1, "{name}: {recipe:?}");
                    recipe
                        .categories
                        .first()
                        .is_none_or(|category| categories.contains(category))
                })
                .inspect(|(name, recipe)| {
                    if recipe
                        .results
                        .iter()
                        .any(|result| matches!(result.r#type, Type::Fluid))
                    {
                        return;
                    }

                    let Some(input_count) = recipe.ingredients.iter().try_fold(
                        0,
                        |time, ingredient| match ingredient {
                            Ingredient::Item { amount, .. } => Some(time + amount),
                            Ingredient::Fluid { .. } => None,
                        },
                    ) else {
                        return;
                    };

                    assert!(
                        recipe.main_product.is_some() || recipe.results.len() == 1,
                        "{name}: {recipe:?}"
                    );
                    let main_index = recipe
                        .main_product
                        .and_then(|name| {
                            recipe.results.iter().position(|result| result.name == name)
                        })
                        .unwrap_or(0);
                    let main_result = &recipe.results[main_index];

                    assert_eq!(main_result.extra_count_fraction, 0.0, "{name}: {recipe:?}");
                    assert_eq!(main_result.probability.average(), 1.0);
                    let amount = main_result.amount.average();
                    if amount != 1.0 {
                        eprintln!("{name}: {recipe:?}");
                    }

                    craftable.insert(
                        main_result.name,
                        Io {
                            craft_time: recipe.energy_required * 60.0 / amount,
                            input_count: input_count as f32 / amount,
                        },
                    );
                })
                .flat_map(|(_, recipe)| {
                    recipe.results.iter().flat_map(|result| {
                        recipe
                            .ingredients
                            .iter()
                            .map(|ingredient| (ingredient.name(), result.name))
                    })
                })
                .map(|(ingredient, result)| (ingredient, result, Empty))
                // .map(|(ingredient, result)| {
                //     (
                //         &*ingredient.to_owned().leak(),
                //         &*result.to_owned().leak(),
                //         Empty,
                //     )
                // })
                .collect::<DiGraphMap<_, _>>();

            // println!("{}", petgraph::dot::Dot::new(&graph));

            // use graph_cycles::Cycles;
            // let cycles = graph.cycles();
            // eprintln!("{:?}", cycles);

            let mut stack = graph
                .nodes()
                .filter(|node| {
                    graph
                        .neighbors_directed(node, petgraph::Direction::Incoming)
                        .count()
                        == 0
                })
                .collect::<Vec<_>>();

            let mut depths = stack
                .iter()
                .map(|node| (*node, 0))
                .collect::<HashMap<_, _>>();
            let mut max_depth = 0;

            while let Some(input) = stack.pop() {
                let input_depth = depths[input];
                for output in graph.neighbors_directed(input, petgraph::Direction::Outgoing) {
                    let output_depth = depths.entry(output).or_insert(0);
                    if *output_depth > input_depth {
                        continue;
                    }

                    *output_depth = input_depth + 1;

                    stack.push(output);

                    if *output_depth > max_depth && craftable.contains_key(output) {
                        max_depth = *output_depth;
                    }
                }
            }

            let mut item_by_depth = vec![Vec::new(); max_depth + 1];
            for (name, depth) in depths
                .into_iter()
                .filter(|(name, _)| craftable.contains_key(name))
            {
                item_by_depth[depth].push(name);
            }
            assert!(item_by_depth[0].is_empty(), "Can't craft depth 0 items");

            let sections = match mode {
                mode @ (Mode::CraftTime | Mode::InputCount) => item_by_depth
                    .into_iter()
                    .enumerate()
                    .skip(1)
                    .map(|(index, items)| {
                        let mut filters = items
                            .into_iter()
                            .map(|name| {
                                let io = &craftable[name];
                                let io = match mode {
                                    Mode::Priority => unreachable!(),
                                    Mode::CraftTime => io.craft_time,
                                    Mode::InputCount => io.input_count,
                                };

                                LogisticFilter {
                                    index: NonZeroU16::MIN,
                                    name,
                                    count: io as i32,
                                }
                            })
                            .collect::<Vec<_>>();

                        filters.sort_unstable_by_key(|filter| filter.name);

                        for (index, filter) in filters.iter_mut().enumerate() {
                            filter.index = NonZeroU16::new((index + 1) as u16).unwrap();
                        }

                        LogisticSection {
                            index: NonZeroU8::new(index as u8).unwrap(),
                            multiplier: 1.0,
                            filters,
                        }
                    })
                    .collect(),
                Mode::Priority => item_by_depth
                    .into_iter()
                    .enumerate()
                    .skip(1)
                    .map(|(index, items)| {
                        let mut filters = items
                            .into_iter()
                            .map(|name| LogisticFilter {
                                index: NonZeroU16::MIN,
                                name,
                                count: 1,
                            })
                            .collect::<Vec<_>>();

                        filters.sort_unstable_by_key(|filter| filter.name);

                        for (index, filter) in filters.iter_mut().enumerate() {
                            filter.index = NonZeroU16::new((index + 1) as u16).unwrap();
                        }

                        LogisticSection {
                            index: NonZeroU8::new(index as u8).unwrap(),
                            multiplier: index as f32,
                            filters,
                        }
                    })
                    .collect(),
            };

            if blueprint {
                let blueprint = BlueprintString::constant_combinator("", sections).encode();
                std::io::stdout().lock().write_all(&blueprint).unwrap();
            } else {
                sections.iter().for_each(|section| {
                    eprintln!("{}: {:.0}x", section.index, section.multiplier);
                    section.filters.iter().for_each(|filter| {
                        eprintln!("- {}: {} = {}", filter.index, filter.name, filter.count);
                    })
                })
            }
        }
    }
}

/// Approximate I/O cost per unit output
struct Io {
    craft_time: f32,
    input_count: f32,
}

#[derive(Debug)]
struct Empty;

impl Display for Empty {
    fn fmt(&self, _: &mut core::fmt::Formatter<'_>) -> std::fmt::Result {
        Ok(())
    }
}

#[derive(Debug, Deserialize)]
struct Data<'a> {
    #[serde(
        borrow,
        deserialize_with = "deserialize_item_map",
        rename = "assembling-machine"
    )]
    machines: Vec<(&'a str, Machine<'a>)>,

    #[serde(borrow, deserialize_with = "deserialize_item_map", rename = "recipe")]
    recipes: Vec<(&'a str, Recipe<'a>)>,

    #[serde(
        borrow,
        deserialize_with = "deserialize_item_map",
        rename = "technology"
    )]
    technologies: Vec<(&'a str, Technology<'a>)>,
}

#[derive(Debug, Deserialize)]
struct Technology<'a> {
    #[serde(borrow, deserialize_with = "deserialize_empty_vec")]
    effects: Vec<Effect<'a>>,
}

#[derive(Debug, Deserialize)]
#[serde(tag = "type", rename_all = "kebab-case")]
enum Effect<'a> {
    UnlockRecipe {
        recipe: &'a str,
    },
    #[serde(other)]
    Other,
}

#[derive(Debug, Deserialize)]
struct Machine<'a> {
    #[serde(borrow, rename = "crafting_categories")]
    categories: Vec<&'a str>,
}

#[derive(Debug, Deserialize)]
struct Recipe<'a> {
    #[serde(default = "default_true")]
    enabled: bool,

    energy_required: f32,
    #[serde(borrow)]
    main_product: Option<&'a str>,

    #[serde(borrow, default)]
    categories: Vec<&'a str>,

    #[serde(borrow, deserialize_with = "deserialize_empty_vec")]
    ingredients: Vec<Ingredient<'a>>,

    #[serde(borrow, deserialize_with = "deserialize_empty_vec")]
    results: Vec<Result<'a>>,
}

#[derive(Debug, Deserialize)]
#[serde(tag = "type", rename_all = "lowercase")]
enum Ingredient<'a> {
    Item { name: &'a str, amount: u16 },
    Fluid { name: &'a str },
}

impl<'a> Ingredient<'a> {
    fn name(&self) -> &'a str {
        match self {
            Self::Item { name, .. } | Self::Fluid { name } => name,
        }
    }
}

#[derive(Debug, Deserialize)]
struct Result<'a> {
    r#type: Type,
    name: &'a str,

    #[serde(flatten)]
    amount: Amount,

    #[serde(flatten)]
    probability: Probability,

    #[serde(default)]
    extra_count_fraction: f32,
}

#[derive(Copy, Clone, Debug, Deserialize)]
#[serde(rename_all = "lowercase")]
enum Type {
    Item,
    Fluid,
}

#[derive(Debug, Deserialize)]
#[serde(untagged)]
enum Amount {
    Fixed { amount: f32 },
    Uniform { amount_min: f32, amount_max: f32 },
}

impl Amount {
    fn average(&self) -> f32 {
        match self {
            Self::Fixed { amount } => *amount,
            Self::Uniform {
                amount_min,
                amount_max,
            } => amount_min + amount_max.max(*amount_min) / 2.0,
        }
    }
}

#[derive(Debug, Deserialize)]
struct Probability {
    #[serde(default = "default_1")]
    independent_probability: f64,

    #[serde(default)]
    shared_probability: SharedProbability,
}

impl Probability {
    fn average(&self) -> f64 {
        self.independent_probability * (self.shared_probability.max - self.shared_probability.min)
    }
}

#[derive(Debug, Deserialize)]
struct SharedProbability {
    min: f64,
    #[serde(default = "default_1")]
    max: f64,
}

impl Default for SharedProbability {
    fn default() -> Self {
        Self { min: 0.0, max: 1.0 }
    }
}

const fn default_true() -> bool {
    true
}

const fn default_1() -> f64 {
    1.0
}
